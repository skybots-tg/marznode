"""Отпечаток набора юзеров — общий формат для ноды и панели.

Панель толкает изменения по одному и до сих пор не имела способа узнать,
доехали ли они. Полная выгрузка ради сверки стоит дорого: на крупной ноде это
десять тысяч записей каждые несколько минут. Отпечаток стоит один хэш.

Формат намеренно простой и описан здесь же, потому что вторая его реализация
живёт в другом репозитории (``app/marznode/users_digest.py`` в панели) и
разойтись они не должны:

* на юзера — строка ``"<id>:<tag>,<tag>,..."``;
* теги внутри строки отсортированы и дедуплицированы;
* строки отсортированы как строки (то есть ``"10:"`` идёт раньше ``"9:"`` —
  это не ошибка, важно лишь чтобы обе стороны сортировали одинаково);
* всё склеено через ``"\n"``, от utf-8 берётся sha256, отдаётся hex.
"""

import hashlib
from typing import Iterable


def users_digest(users: Iterable[tuple[int, Iterable[str]]]) -> str:
    """sha256 по парам (id юзера, его инбаунд-теги)."""
    lines = sorted(
        "{}:{}".format(uid, ",".join(sorted(set(tags)))) for uid, tags in users
    )
    return hashlib.sha256("\n".join(lines).encode("utf-8")).hexdigest()
